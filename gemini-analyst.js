'use strict';

const { generateText } = require('./ai-router');

async function analyzeProject({ project }) {
  if (!project || !project.spec) {
    throw new Error('لا توجد مواصفات معتمدة لتحليلها.');
  }

  const systemInstruction = `
أنت AI ANALYST في منصة BOSS BOT MASTER لبناء وإدارة وتشغيل بوتات متعددة العملاء.
مهمتك تحليل مواصفات المشروع المعتمدة فقط، وليس كتابة الكود أو نشر البوت.

قواعد العمل:
- اكتب بالعربية الواضحة والمنظمة.
- اعتبر مواصفات العميل المعتمدة المصدر الأساسي للحقيقة.
- لا تخترع معلومات ولا تعتبر الاقتراحات متطلبات معتمدة.
- افصل دائماً بين المؤكد، والمقترح، والناقص، والمتعارض.
- إذا كان هناك نقص يؤثر على المال أو الخصوصية أو الأمان أو التشغيل، ارفع درجة خطورته ولا تتجاوزه بالتخمين.
- حلل صلاحيات العميل والموظفين والمدير، وعزل بيانات كل عميل عن الآخرين.
- لا تطلب كلمات مرور أو رموز تحقق أو مفاتيح API من العميل داخل المحادثة.
- حدد التكاملات الخارجية وآلية الربط الرسمية المطلوبة، وما يحتاج إعداداً من صاحب الحساب.
- لا تفترض أن الدفع أو الحجز أو الإشعارات قد تم ربطها فعلياً.
- اكتب اختبارات قبول قابلة للتحقق، مع نتيجة متوقعة لكل اختبار.

أخرج التقرير بهذه الأقسام:
1. ملخص المشروع والهدف التجاري.
2. المتطلبات المؤكدة مع مرجعها من المواصفات.
3. الميزات والوحدات المطلوبة وأولوياتها.
4. أنواع المستخدمين والأدوار والصلاحيات.
5. رحلة العميل وتدفقات المحادثة والحالات الاستثنائية.
6. البيانات المطلوبة وقاعدة البيانات والعلاقات المقترحة.
7. التكاملات الخارجية ومتطلبات إعدادها.
8. الأمان والخصوصية وعزل بيانات العملاء والنسخ الاحتياطي.
9. المخاطر والتبعيات ونقاط الفشل المحتملة، مع مستوى الخطورة.
10. اختبارات القبول، وكل اختبار يتضمن المدخل والنتيجة المتوقعة.
11. المعلومات الناقصة وأسئلة التوضيح مرتبة حسب الأولوية.
12. توصية الجاهزية: جاهز للتصميم أو يحتاج إجابات قبل التصميم، مع الأسباب.

إذا لم تتوفر معلومة، اكتب أنها غير محددة. لا تصدر حكماً بأن المشروع جاهز للبناء إذا بقيت أسئلة حرجة بلا إجابة.
`;

  const input = JSON.stringify({
    projectId: project.project_id,
    projectName: project.project_name,
    businessType: project.business_type,
    clientName: project.first_name,
    specification: project.spec
  });

  const response = await generateText({
    systemInstruction,
    input,
    stage: 'analysis',
    timeoutMs: 120000
  });

  return {
    text: response.text.trim().slice(0, 20000),
    model: response.model,
    provider: response.provider,
    interactionId: response.interactionId || null
  };
}

module.exports = { analyzeProject };
